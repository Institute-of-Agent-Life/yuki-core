"""Generate SDK types, conformance data and the public method index from the sole wire IDL."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IDL = ROOT / "protocol/plugin/handshake.schema.json"


def rust_type(field):
    if "$ref" in field:
        return field["$ref"].split("/")[-1]
    if field["type"] == "array":
        return "Vec<" + rust_type(field["items"]) + ">"
    return {"string": "String", "integer": "u16"}[field["type"]]


def py_type(field):
    if "$ref" in field:
        return field["$ref"].split("/")[-1]
    if field["type"] == "array":
        return "list[" + py_type(field["items"]) + "]"
    return {"string": "str", "integer": "int"}[field["type"]]


def generate():
    raw = IDL.read_bytes()
    schema = json.loads(raw)
    meta = schema["x-yuki"]
    rust = [
        "// Generated by protocol/plugin/generate.py from handshake.schema.json.",
        "use serde::{Deserialize, Serialize};",
        "",
    ]
    py = [
        '"""Generated from handshake.schema.json. Run protocol/plugin/generate.py to update."""',
        "from dataclasses import dataclass, field",
        "",
    ]
    for name, definition in schema["$defs"].items():
        rust += [
            "#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]",
            "pub struct " + name + " {",
        ]
        py += ["@dataclass", "class " + name + ":"]
        for prop, shape in sorted(
            definition["properties"].items(),
            key=lambda pair: pair[0] not in definition["required"],
        ):
            optional = prop not in definition["required"]
            if optional:
                if shape.get("type") != "array":
                    raise ValueError("unsupported optional field")
                rust.append("    #[serde(default)]")
            rust.append(f"    pub {prop}: {rust_type(shape)},")
            py.append(
                f"    {prop}: {py_type(shape)}"
                + (" = field(default_factory=list)" if optional else "")
            )
        rust += [
            "}",
            "",
            f"impl crate::Validate for {name} {{",
            "    fn validate(&self) -> bool {",
        ]
        checks = []
        for prop, shape in definition["properties"].items():
            expr = "self." + prop
            if "$ref" in shape:
                checks.append(expr + ".validate()")
            elif shape["type"] == "string":
                checks.append(
                    f"({shape['minLength']}..={shape['maxLength']}).contains(&{expr}.chars().count())"
                )
            elif shape["type"] == "array":
                checks.append(f"{expr}.len() <= {shape['maxItems']}")
                item = shape["items"]
                if "$ref" in item:
                    checks.append(expr + ".iter().all(crate::Validate::validate)")
                elif item["type"] == "string":
                    checks.append(
                        f"{expr}.iter().all(|v| ({item['minLength']}..={item['maxLength']}).contains(&v.chars().count()))"
                    )
        rust += [
            "        " + (" &&\n            ".join(checks) if checks else "true"),
            "    }",
            "}",
            "",
        ]
        py += ["", ""]
    rust.append(
        "pub const MAX_FRAME_BYTES: usize = " + str(meta["max_frame_bytes"]) + ";"
    )
    rust.append(
        "pub const SCHEMA_REVISION: u16 = " + str(meta["schema_revision"]) + ";"
    )
    rust.append(
        "pub const VERSIONS: &[(u16,u16)] = &["
        + ",".join(f"({v['major']},{v['minor']})" for v in meta["versions"])
        + "];"
    )
    for const, key in [("FEATURES", "features"), ("EXTENSIONS", "extension_points")]:
        rust.append(
            f"pub const {const}: &[&str] = &["
            + ",".join(json.dumps(v) for v in meta[key])
            + "];"
        )
    rust.append(
        "pub const METHODS: &[(&str,u16)] = &["
        + ",".join(
            f"({json.dumps(k)},{v['revision']})" for k, v in meta["methods"].items()
        )
        + "];"
    )
    for name, code in meta["errors"].items():
        rust.append(f"pub const {name.upper()}: i64 = {code};")
    py.append("CONTRACT = " + repr(meta))
    version = meta["versions"][-1]
    offer = {
        "versions": {"min": version, "max": version},
        "required_features": meta["features"],
        "optional_features": [],
        "manifest_revision": "fixture-r1",
        "declarations": [],
    }
    reply = {
        "version": version,
        "features": meta["features"],
        "schema_revision": meta["schema_revision"],
        "extension_points": meta["extension_points"],
        "namespace": "fixture.plugin",
        "grants": [],
        "method_revisions": [
            {"name": k, "revision": v["revision"]} for k, v in meta["methods"].items()
        ],
        "manifest_revision": "fixture-r1",
    }
    lines = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": offer},
        {"jsonrpc": "2.0", "id": 1, "result": reply},
    ]
    index = {
        "schema_sha256": hashlib.sha256(raw).hexdigest(),
        **{
            k: meta[k] for k in ("status", "schema_revision", "sdk_versions", "methods")
        },
    }
    host=json.loads((ROOT/"protocol/plugin/gateway/host-preview.json").read_bytes())
    for group in ("personal","media","composition","aux-model"):
        extension=json.loads((ROOT/f"protocol/plugin/{group}/methods.json").read_bytes())
        if host["methods"].keys() & extension["methods"].keys():
            raise ValueError("duplicate host methods")
        host["methods"].update(extension["methods"])
    host_bytes=(json.dumps(host,indent=2,ensure_ascii=False)+"\n").encode()
    return {
        ROOT / "sdk/rust/src/generated.rs": ("\n".join(rust) + "\n").encode(),
        ROOT / "sdk/python/yuki_plugin_sdk/generated.py": (
            "\n".join(py) + "\n"
        ).encode(),
        ROOT / "sdk/python/yuki_plugin_sdk/handshake.schema.json": raw,
        ROOT / "sdk/python/yuki_plugin_sdk/host-preview.json": host_bytes,
        ROOT / "sdk/rust/src/host-preview.json": host_bytes,
        ROOT / "protocol/plugin/method-index.json": (
            json.dumps(index, sort_keys=True, indent=2) + "\n"
        ).encode(),
        ROOT / "protocol/plugin/handshake.ndjson": "".join(
            json.dumps(row, sort_keys=True, separators=(",", ":")) + "\n"
            for row in lines
        ).encode(),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    for file, data in generate().items():
        if check:
            if not file.is_file() or file.read_bytes() != data:
                raise SystemExit("stale generated file: " + str(file))
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_bytes(data)


if __name__ == "__main__":
    main()
